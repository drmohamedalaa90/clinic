(() => {

  /*
   * Public Booking Time Guard
   *
   * Purpose:
   * - Remove appointment slots that have already passed.
   * - Never interfere while book.html is still loading slots.
   * - Avoid MutationObserver loops.
   * - Keep mobile booking responsive.
   */


  let running = false;



  function closePassedPublicSlots() {

    if (running) {
      return;
    }


    const slotSelect =
      document.getElementById(
        'clinicSlot'
      );


    const dateSelect =
      document.getElementById(
        'clinicDate'
      );


    if (
      !slotSelect
      ||
      !dateSelect
      ||
      !dateSelect.value
    ) {
      return;
    }



    /*
     * A real slot option generated by book.html
     * contains "|" in its value.
     *
     * Example:
     * 2026-08-13T15:00:00+03:00|2026-08-13T16:00:00+03:00
     *
     * While book.html is loading, the select may contain only:
     * "جاري تحميل الساعات..."
     *
     * We MUST leave that state alone.
     */

    const optionValues =
      Array.from(
        slotSelect.options
      )
      .map(
        option =>
          option.value
          ||
          ''
      );


    const hasRealSlots =
      optionValues.some(
        value =>
          value.includes(
            '|'
          )
      );


    if (!hasRealSlots) {

      /*
       * Do nothing.
       *
       * book.html may still be:
       * - loading slots
       * - waiting for day selection
       * - showing an RPC error
       *
       * Never overwrite those temporary states.
       */

      return;
    }



    running = true;


    try {

      const now =
        Date.now();



      /*
       * Remove only slots whose actual start time
       * has already passed.
       */

      Array.from(
        slotSelect.options
      )
      .forEach(
        option => {

          if (
            !option.value
            ||
            !option.value.includes(
              '|'
            )
          ) {
            return;
          }


          const [
            start
          ] =
            option.value.split(
              '|'
            );


          const timestamp =
            new Date(
              start
            ).getTime();


          if (
            Number.isFinite(
              timestamp
            )
            &&
            timestamp <= now
          ) {

            option.remove();
          }
        }
      );



      /*
       * Count actual usable slots remaining.
       */

      const usableSlots =
        Array.from(
          slotSelect.options
        )
        .filter(
          option =>
            option.value
            &&
            option.value.includes(
              '|'
            )
        );



      if (!usableSlots.length) {

        /*
         * Prevent repeatedly rewriting the same select.
         * That was one of the causes of the old loop.
         */

        if (
          slotSelect.dataset
            .timeGuardState
          !==
          'closed'
        ) {

          slotSelect.dataset
            .timeGuardState =
              'closed';


          slotSelect.disabled =
            true;


          slotSelect.innerHTML = `
            <option value="">
              انتهت المواعيد المتاحة لهذا اليوم
            </option>
          `;


          const message =
            document.getElementById(
              'availabilityMessage'
            );


          if (message) {

            message.textContent =
              'انتهت الساعات المتاحة لهذا اليوم. اختر يوماً آخر.';
          }
        }

      }
      else {

        /*
         * Valid slots remain.
         */

        slotSelect.dataset
          .timeGuardState =
            'open';


        slotSelect.disabled =
          false;
      }

    }
    finally {

      running = false;
    }
  }



  function startPublicBookingTimeGuard() {

    const slotSelect =
      document.getElementById(
        'clinicSlot'
      );


    if (!slotSelect) {

      /*
       * The booking UI may not have rendered yet.
       * Try once more shortly.
       */

      setTimeout(
        startPublicBookingTimeGuard,
        300
      );

      return;
    }



    /*
     * Watch ONLY clinicSlot.
     *
     * Do NOT observe document.body.
     * That caused excessive callbacks and could create
     * a mutation loop while slots were loading.
     */

    const observer =
      new MutationObserver(
        () => {

          /*
           * Let book.html finish rendering all slot options
           * before we inspect them.
           */

          requestAnimationFrame(
            closePassedPublicSlots
          );
        }
      );


    observer.observe(
      slotSelect,
      {
        childList: true
      }
    );



    /*
     * Recheck every 30 seconds so a slot that passes
     * while the page is open becomes unavailable.
     */

    setInterval(
      closePassedPublicSlots,
      30000
    );



    /*
     * Initial check.
     */

    closePassedPublicSlots();
  }



  if (
    document.readyState ===
    'loading'
  ) {

    document.addEventListener(
      'DOMContentLoaded',
      startPublicBookingTimeGuard,
      {
        once: true
      }
    );

  }
  else {

    startPublicBookingTimeGuard();
  }

})();
